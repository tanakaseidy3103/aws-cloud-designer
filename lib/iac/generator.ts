/**
 * Terraform generator: InfraModel → set of .tf files.
 *
 * Guarantees (each covered by tests):
 *  - Output is a pure function of the model (no timestamps, no random ids).
 *  - No credentials, account IDs, AMI IDs, VPC/subnet IDs are hardcoded.
 *  - Every file passes `terraform fmt -check` and the set passes
 *    `terraform validate` for every bundled template.
 *  - Resources the model marks as not generatable are skipped and reported,
 *    never emitted half-configured.
 */

import type { InfraModel } from "@/lib/infra/model";
import { validateModel, type ValidationWarning } from "@/lib/validation";
import { analyzeSecurity, type SecurityReport } from "@/lib/security";
import { createContext, type SectionFile } from "./context";
import { renderFile, type BodyItem } from "./hcl";
import { generateNetwork } from "./network";
import { mainFile, outputsFile, providersFile, tfvarsExample, variablesFile } from "./root";

export interface GeneratedTerraform {
  /** File name → contents, in a stable order. */
  files: Record<string, string>;
  /** Architecture validation results (errors explain skipped resources). */
  diagnostics: ValidationWarning[];
  /** Security findings for the generated configuration. */
  security: SecurityReport;
  skipped: { resourceId: string; reason: string }[];
  /** False when validation reported errors: review before using the output. */
  ready: boolean;
}

type Section = (ctx: ReturnType<typeof createContext>) => SectionFile | SectionFile[] | null;

/** Order matters only for readability of each file; HCL is declarative. */
export const SECTIONS: Section[] = [generateNetwork];

const HEADER = (model: InfraModel) =>
  [
    `Generated by CloudSentinel from architecture "${model.name.replace(/[\r\n]/g, " ")}".`,
    "Review `terraform plan` before applying. Nothing in this file is applied automatically.",
  ].join("\n");

export function generateTerraformFromModel(model: InfraModel): GeneratedTerraform {
  const ctx = createContext(model);
  const validation = validateModel(model);

  const sectionFiles = new Map<string, BodyItem[]>();
  for (const section of SECTIONS) {
    const result = section(ctx);
    for (const f of result ? (Array.isArray(result) ? result : [result]) : []) {
      if (f.items.length === 0) continue;
      sectionFiles.set(f.file, [...(sectionFiles.get(f.file) ?? []), ...f.items]);
    }
  }

  const files: Record<string, string> = {};
  files["main.tf"] = renderFile(mainFile(ctx), HEADER(model));
  files["providers.tf"] = renderFile(providersFile(ctx));
  files["variables.tf"] = renderFile(variablesFile(ctx));
  for (const [name, items] of sectionFiles) files[name] = renderFile(items);
  files["outputs.tf"] = renderFile(outputsFile(ctx));
  files["terraform.tfvars.example"] = tfvarsExample(ctx);

  return {
    files,
    diagnostics: validation.warnings,
    security: analyzeSecurity(model),
    skipped: ctx.skipped,
    ready: validation.isValid,
  };
}
